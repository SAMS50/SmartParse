"""Run regressions while preserving the known legacy timing-output side effect."""
import hashlib
import json
from pathlib import Path
import subprocess
import sys

ROOT=Path(__file__).resolve().parents[2]


def snapshot():
    files=subprocess.check_output(['git','ls-files','results','acceptance/output','phase6'],cwd=ROOT,text=True).splitlines()
    files=[f for f in files if not f.startswith('phase6/v12/')]
    files+= [p.relative_to(ROOT).as_posix() for p in (ROOT/'acceptance/output').rglob('*') if p.is_file()]
    return {f:hashlib.sha256((ROOT/f).read_bytes()).hexdigest() for f in sorted(set(files)) if (ROOT/f).is_file()}


def main():
    before=snapshot();path=ROOT/'results/verified_performance.csv';saved=path.read_bytes()
    try:
        result=subprocess.run([sys.executable,'-m','unittest','discover'],cwd=ROOT,timeout=600)
    finally:
        # This file is known to be regenerated by legacy tests. Restore the exact
        # pre-run bytes, never a guessed version and never untracked user files.
        if path.read_bytes()!=saved:path.write_bytes(saved)
    after=snapshot();changed=[f for f,digest in before.items() if after.get(f)!=digest]
    out=ROOT/'.studio-artifacts/m12';out.mkdir(parents=True,exist_ok=True)
    (out/'preservation.json').write_text(json.dumps(dict(checked_files=len(before),changed=changed,
        original_acceptance_files_preserved=not any(f.startswith('acceptance/output/') for f in changed),
        legacy_performance_bytes_restored=True,test_exit_code=result.returncode),indent=2),encoding='utf-8')
    print(f'Preservation: {len(before)} files checked, {len(changed)} changed')
    if changed:raise SystemExit('Historical source/artifacts changed: '+', '.join(changed))
    raise SystemExit(result.returncode)


if __name__=='__main__':main()
